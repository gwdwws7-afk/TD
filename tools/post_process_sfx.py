"""
Emberline Defense SFX post-processor.

Reads the raw SFX generated by batch_text_to_music (typically 30-200s of
ambient/atmosphere output) and produces a game-ready SFX trimmed to the
target duration from `design/spec/minimax_prompt_full.txt`, converted to
mono or stereo per spec, with a 5 ms fade in/out, and normalized to the
target integrated loudness in LUFS.

Usage:
    python post_process_sfx.py [--dry-run]

Inputs:
    output/audio/sfx/**/*.wav     (raw, long)

Outputs:
    output/audio/sfx_final/**/*.wav
"""

