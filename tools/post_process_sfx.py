def read_wav(path: Path):
    """Read any PCM WAV into float64 numpy in [-1, 1], shape (n,) or (n, ch)."""
    with wave.open(str(path), "rb") as wf:
        sr = wf.getframerate()
        n_ch = wf.getnchannels()
        sw = wf.getsampwidth()
        n = wf.getnframes()
        raw = wf.readframes(n)
    if sw == 2:
        samples = np.frombuffer(raw, dtype="<i2").astype(np.float64) / 32768.0
    elif sw == 3:
        b = np.frombuffer(raw, dtype=np.uint8).reshape(-1, 3)
        i = (b[:, 0].astype(np.int32)
             | (b[:, 1].astype(np.int32) << 8)
             | (b[:, 2].astype(np.int32) << 16))
        # sign extend
        i = (i ^ 0x800000) - 0x800000
        samples = i.astype(np.float64) / 8388608.0
    elif sw == 4:
        samples = np.frombuffer(raw, dtype="<i4").astype(np.float64) / 2147483648.0
    else:
        raise ValueError(f"unsupported sample width {sw}")
    if n_ch > 1:
        samples = samples.reshape(-1, n_ch)
    return samples, sr, n_ch


def write_wav(path: Path, samples: np.ndarray, sr: int):
    """Write float64 [-1, 1] numpy to 16-bit PCM WAV."""
    if samples.ndim == 1:
        samples = samples.reshape(-1, 1)
    # peak limiter at PEAK_CEIL_DBFS
    peak = float(np.max(np.abs(samples))) if samples.size else 0.0
    if peak > 0:
        target = 10 ** (PEAK_CEIL_DBFS / 20)
        if peak > target:
            samples = samples * (target / peak)
    # clip
    samples = np.clip(samples, -1.0, 1.0)
    i16 = (samples * 32767.0).astype("<i2")
    n_ch = i16.shape[1]
    path.parent.mkdir(parents=True, exist_ok=True)
    with wave.open(str(path), "wb") as wf:
        wf.setnchannels(n_ch)
        wf.setsampwidth(2)
        wf.setframerate(sr)
        wf.writeframes(i16.tobytes())


def find_sound_start(samples: np.ndarray, sr: int) -> int:
    """Index of first sample where peak amplitude exceeds silence threshold."""
    if samples.ndim == 1:
        peak = np.abs(samples)
    else:
        peak = np.max(np.abs(samples), axis=1)
    above = np.where(peak > SILENCE_THRESH)[0]
    return int(above[0]) if len(above) else 0


def find_loudest_window(samples: np.ndarray, target_n: int) -> int:
    """Start index of the target_n-sample window with the highest RMS energy.

    This preserves the 'attack' / peak moment of the source, which is what a
    game SFX actually needs (rather than the first non-silent moment, which
    can land in a quiet intro).
    """
    if samples.ndim == 1:
        peak = np.abs(samples)
    else:
        peak = np.max(np.abs(samples), axis=1)
    if peak.shape[0] <= target_n:
        return 0
    sq = peak ** 2
    cs = np.concatenate([[0.0], np.cumsum(sq)])
    # window sum for window starting at i = cs[i+target_n] - cs[i]
    window_sums = cs[target_n:] - cs[: cs.shape[0] - target_n]
    return int(np.argmax(window_sums))


def measure_lufs(samples: np.ndarray, sr: int) -> float:
    """Integrated LUFS, returns -inf if too short / silent for measurement."""
    if samples.ndim == 1:
        s = samples.reshape(-1, 1)
    else:
        s = samples
    if np.max(np.abs(s)) < 1e-6 or s.shape[0] < int(0.4 * sr):
        return float("-inf")
    meter = pyln.Meter(sr)
    try:
        return float(meter.integrated_loudness(s))
    except Exception:
        return float("-inf")


def normalize_lufs(samples: np.ndarray, sr: int, target_lufs: float,
                   peak_ceil_dbfs: float = PEAK_CEIL_DBFS) -> np.ndarray:
    """Strict LUFS-target with peak ceiling via hard clip.

    1) measure integrated LUFS, compute gain to hit target
    2) apply gain
    3) hard-clip at peak_ceil_dbfs (game-SFX convention; mild distortion
       is acceptable and the alternative is to leave the file 10+ dB too
       quiet, which makes it useless in a busy mix)

    For clips < 0.4s (LUFS unmeasurable), fall back to peak normalization
    at the ceiling.
    """
    measured = measure_lufs(samples, sr)
    if measured == float("-inf"):
        return peak_normalize(samples, peak_ceil_dbfs)
    desired_gain_db = target_lufs - measured
    boosted = samples * (10 ** (desired_gain_db / 20))
    threshold = 10 ** (peak_ceil_dbfs / 20)
    return np.clip(boosted, -threshold, threshold)


def peak_normalize(samples: np.ndarray, target_dbfs: float) -> np.ndarray:
    peak = float(np.max(np.abs(samples))) if samples.size else 0.0
    if peak <= 0:
        return samples
    target = 10 ** (target_dbfs / 20)
    return samples * (target / peak)


def to_mono(samples: np.ndarray) -> np.ndarray:
    if samples.ndim == 1:
        return samples
    return samples.mean(axis=1)


def apply_fade(samples: np.ndarray, sr: int, fade_s: float = FADE_S) -> np.ndarray:
    """Apply 5 ms fade-in at start and 5 ms fade-out at end."""
    n = samples.shape[0]
    fade = max(1, int(fade_s * sr))
    fade = min(fade, n // 2)
    if fade <= 0:
        return samples
    env = np.ones(n, dtype=np.float64)
    env[:fade] = np.linspace(0.0, 1.0, fade)
    env[-fade:] = np.linspace(1.0, 0.0, fade)
    if samples.ndim == 1:
        return samples * env
    return samples * env[:, None]


def process_one(in_path: Path, out_path: Path, duration: float,
                lufs: float, mono: bool, dry_run: bool = False):
    samples, sr, n_ch = read_wav(in_path)
    # resample not needed (we requested 44100 from generator)
    if sr != SR:
        # minimal: just trim using original SR; write_wav will preserve
        pass

    # find the loudest target-duration window in the source, so the
    # output SFX preserves the attack/peak moment rather than a quiet intro
    target_n = int(duration * sr)
    start = find_loudest_window(samples, target_n)
    samples = samples[start:start + target_n]

    # trim/pad to target duration
    target_n = int(duration * sr)
    if samples.shape[0] >= target_n:
        samples = samples[:target_n]
    else:
        pad = np.zeros((target_n - samples.shape[0],) if samples.ndim == 1
                       else (target_n - samples.shape[0], samples.shape[1]))
        samples = np.concatenate([samples, pad], axis=0)

    # mono / stereo
    if mono:
        samples = to_mono(samples)
    elif samples.ndim == 1:
        # duplicate to stereo so output is true stereo
        samples = np.stack([samples, samples], axis=1)

    # fade in/out
    samples = apply_fade(samples, sr)

    # normalize
    samples = normalize_lufs(samples, sr, lufs)

    if not dry_run:
        write_wav(out_path, samples, sr)
    return samples.shape[0] / sr, sr


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--input", default="E:/TD/output/audio/sfx")
    ap.add_argument("--output", default="E:/TD/output/audio/sfx_final")
    args = ap.parse_args()

    in_root = Path(args.input)
    out_root = Path(args.output)

    files = sorted(in_root.rglob("*.wav"))
    if not files:
        print(f"no wav files under {in_root}", file=sys.stderr)
        return 1

    print(f"processing {len(files)} SFX -> {out_root}")
    ok = 0
    skipped = 0
    failed = 0
    for f in files:
        name = f.stem
        if name not in SPEC:
            print(f"  SKIP {name} (no spec)")
            skipped += 1
            continue
        dur, lufs, mono = SPEC[name]
        rel = f.relative_to(in_root)
        out = out_root / rel
        try:
            actual_dur, sr = process_one(f, out, dur, lufs, mono,
                                          dry_run=args.dry_run)
            ch = "mono" if mono else "stereo"
            tag = "(dry)" if args.dry_run else ""
            print(f"  OK  {name:<22} -> {rel}  {actual_dur:.3f}s / {dur}s  "
                  f"target {lufs} LUFS  {ch}  {tag}")
            ok += 1
        except Exception as e:
            print(f"  FAIL {name}: {e}")
            failed += 1

    print(f"\nsummary: ok={ok} skipped={skipped} failed={failed}")
    return 0 if failed == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
